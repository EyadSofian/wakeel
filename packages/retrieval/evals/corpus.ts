const locales = ["msa", "egyptian", "gulf", "code-switched"] as const;
function render(template: string, entity: number) {
  const data = {
    code: `SRJ-${1001 + entity}`,
    n: String(entity + 3),
    percent: String(70 + entity * 2),
    days: String(60 + entity * 10),
    hour: String(17 + (entity % 4)),
  };
  return template.replace(/\{(code|n|percent|days|hour)\}/g, (_, key: keyof typeof data) => data[key]);
}

